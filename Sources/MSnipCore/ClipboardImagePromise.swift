/// 剪贴板数据消费探针（用于判断前台编辑器在收到 ⌘V 时是否读取了图像数据）
public final class ClipboardConsumptionProbe: @unchecked Sendable {
    private let lock = NSLock()
    private var imageRequested = false
    private var stringRequested = false
    public var onImageRequested: (@Sendable () -> Void)?

    public init(onImageRequested: (@Sendable () -> Void)? = nil) {
        self.onImageRequested = onImageRequested
    }

    public var wasImageRequested: Bool {
        lock.lock()
        defer { lock.unlock() }
        return imageRequested
    }

    public var wasStringRequested: Bool {
        lock.lock()
        defer { lock.unlock() }
        return stringRequested
    }

    func markImageRequested() {
        let callback: (@Sendable () -> Void)?
        lock.lock()
        let first = !imageRequested
        imageRequested = true
        callback = first ? onImageRequested : nil
        lock.unlock()
        callback?()
    }

    func markStringRequested() {
        lock.lock()
        stringRequested = true
        lock.unlock()
    }
}

/// 共享的 2.5 秒闲置自动压缩图像容器：避免 `SmartClipboardProjectionManager` 与 `Provider` 双重强持未压缩 5K 位图
public final class ClipboardImageBacking: @unchecked Sendable {
    private let lock = NSLock()
    private var rawImage: CGImage?
    private var compactedPNG: Data?
    public let scaleFactor: CGFloat

    public init(cgImage: CGImage, scaleFactor: CGFloat) {
        self.rawImage = cgImage
        self.scaleFactor = max(1.0, scaleFactor)
        scheduleIdleCompaction()
    }

    private func scheduleIdleCompaction() {
        DispatchQueue.global(qos: .utility).asyncAfter(deadline: .now() + 2.5) { [weak self] in
            guard let self else { return }
            let imgToCompact: CGImage? = self.lock.withLock { (self.compactedPNG == nil) ? self.rawImage : nil }
            guard let img = imgToCompact,
                  let png = ClipboardImagePromise.encodePNG(cgImage: img, scaleFactor: self.scaleFactor) else { return }
            self.lock.withLock { self.compactedPNG = png; self.rawImage = nil }
        }
    }

    func obtainPNGData() -> Data? {
        let state: (Data?, CGImage?) = lock.withLock { (compactedPNG, rawImage) }
        if let png = state.0 { return png }
        guard let img = state.1, let png = ClipboardImagePromise.encodePNG(cgImage: img, scaleFactor: scaleFactor) else { return nil }
        lock.withLock { compactedPNG = png; rawImage = nil }
        return png
    }

    func obtainTransientCGImage() -> CGImage? {
        let state: (CGImage?, Data?) = lock.withLock { (rawImage, compactedPNG) }
        if let img = state.0 { return img }
        guard let png = state.1 else { return nil }
        let opts: [CFString: Any] = [kCGImageSourceShouldCache: false]
        guard let src = CGImageSourceCreateWithData(png as CFData, opts as CFDictionary) else { return nil }
        return CGImageSourceCreateImageAtIndex(src, 0, opts as CFDictionary)
    }

    public func releaseAll() { lock.withLock { rawImage = nil; compactedPNG = nil } }
}

/// 剪贴板零阻塞延迟图像提供器（`NSPasteboardItemDataProvider`）：
/// 按下回车/双击复制截图时主线程 `<0.3ms` 瞬时返回，仅当目标应用真正执行粘贴 (`⌘V`) 时才按需编码 PNG / TIFF。
public enum ClipboardImagePromise {
    private static let lock = NSLock()
    private static var activeProviders: [ObjectIdentifier: Provider] = [:]

    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// 将高清 `CGImage` 以延迟承诺（Promise）方式写入指定剪贴板（支持按前台终端/编辑器/访达动态提供文件 URL 与路径）
    @discardableResult
    public static func write(
        cgImage: CGImage,
        scaleFactor: CGFloat,
        to pasteboard: NSPasteboard = .general,
        mode: ClipboardProjectionMode = .imageOnly,
        transient: Bool = false,
        fileBox: ClipboardFileBox? = nil,
        probe: ClipboardConsumptionProbe? = nil
    ) -> Int {
        write(
            backing: ClipboardImageBacking(cgImage: cgImage, scaleFactor: scaleFactor),
            to: pasteboard, mode: mode, transient: transient, fileBox: fileBox, probe: probe, onFinished: nil
        )
    }

    /// 复用已建共享压缩容器写入剪贴板（用于多应用动态投影，杜绝 5K 原图长期驻留）
    @discardableResult
    public static func write(
        backing: ClipboardImageBacking,
        to pasteboard: NSPasteboard = .general,
        mode: ClipboardProjectionMode = .imageOnly,
        transient: Bool = false,
        fileBox: ClipboardFileBox? = nil,
        probe: ClipboardConsumptionProbe? = nil,
        onFinished: (@Sendable () -> Void)? = nil
    ) -> Int {
        let provider = Provider(
            backing: backing,
            fileBox: fileBox ?? ClipboardFileBox(),
            probe: probe,
            onFinished: onFinished
        )
        let id = ObjectIdentifier(provider)
        lock.lock()
        activeProviders[id] = provider
        lock.unlock()

        var types: [NSPasteboard.PasteboardType] = [.png, .tiff]
        switch mode {
        case .imageOnly:
            break
        case .imageAndFileURL:
            types.append(.fileURL)
        case .terminalImageAndPath:
            types.append(.fileURL)
            types.append(.string)
        }

        let item = NSPasteboardItem()
        item.setDataProvider(provider, forTypes: types)
        if transient {
            item.setData(Data(), forType: transientType)
            item.setData(Data(), forType: autoGeneratedType)
        }
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    /// 使用原生 `ImageIO` 将 `CGImage` 编码为保留 Retina 逻辑 DPI 的标准 PNG 数据
    public static func encodePNG(cgImage: CGImage, scaleFactor: CGFloat) -> Data? {
        let out = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(out, UTType.png.identifier as CFString, 1, nil) else {
            return nil
        }
        let dpi = 72.0 * max(1.0, Double(scaleFactor))
        let props: [CFString: Any] = [
            kCGImagePropertyDPIWidth: dpi,
            kCGImagePropertyDPIHeight: dpi
        ]
        CGImageDestinationAddImage(dest, cgImage, props as CFDictionary)
        guard CGImageDestinationFinalize(dest) else { return nil }
        return out as Data
    }

    /// 使用 `NSBitmapImageRep` 生成保留逻辑点尺寸的 TIFF 数据（供 Keynote / Pages / 预览等原生应用粘贴）
    public static func encodeTIFF(cgImage: CGImage, scaleFactor: CGFloat) -> Data? {
        let s = max(1.0, scaleFactor)
        let rep = NSBitmapImageRep(cgImage: cgImage)
        rep.size = NSSize(
            width: CGFloat(cgImage.width) / s,
            height: CGFloat(cgImage.height) / s
        )
        return rep.tiffRepresentation
    }

    private final class Provider: NSObject, NSPasteboardItemDataProvider, @unchecked Sendable {
        private let stateLock = NSLock()
        private var backing: ClipboardImageBacking?
        let fileBox: ClipboardFileBox
        let probe: ClipboardConsumptionProbe?
        private let onFinished: (@Sendable () -> Void)?

        init(backing: ClipboardImageBacking, fileBox: ClipboardFileBox, probe: ClipboardConsumptionProbe?, onFinished: (@Sendable () -> Void)?) {
            self.backing = backing
            self.fileBox = fileBox
            self.probe = probe
            self.onFinished = onFinished
            super.init()
        }

        func pasteboard(
            _ pasteboard: NSPasteboard?,
            item: NSPasteboardItem,
            provideDataForType type: NSPasteboard.PasteboardType
        ) {
            guard let b = stateLock.withLock({ backing }) else { return }
            if type == .png {
                probe?.markImageRequested()
                if let data = b.obtainPNGData() { item.setData(data, forType: .png) }
            } else if type == .tiff {
                probe?.markImageRequested()
                if let cg = b.obtainTransientCGImage(),
                   let data = ClipboardImagePromise.encodeTIFF(cgImage: cg, scaleFactor: b.scaleFactor) {
                    item.setData(data, forType: .tiff)
                }
            } else if type == .fileURL {
                probe?.markImageRequested()
                if let png = b.obtainPNGData(), let url = fileBox.materializeURL(pngData: png) {
                    item.setData(url.dataRepresentation, forType: .fileURL)
                }
            } else if type == .string {
                probe?.markStringRequested()
                if let png = b.obtainPNGData(), let url = fileBox.materializeURL(pngData: png) {
                    item.setString(url.path, forType: .string)
                }
            }
        }

        func pasteboardFinishedWithDataProvider(_ pasteboard: NSPasteboard) {
            stateLock.withLock { backing = nil }
            let id = ObjectIdentifier(self)
            ClipboardImagePromise.lock.withLock { _ = ClipboardImagePromise.activeProviders.removeValue(forKey: id) }
            onFinished?()
        }
    }
}

// MARK: - 终端粘贴路径兼容适配器

/// 剪贴板图像按前台应用与编辑器焦点动态投影策略
public enum ClipboardProjectionMode: Equatable, Sendable {
    /// 普通应用与编辑器编辑区/AI 聊天框：纯净 `[.png, .tiff]`，零路径干扰
    case imageOnly
    /// 访达（Finder）：`[.png, .tiff, .fileURL]`，支持文件夹内直接 `⌘V` 落盘 PNG
    case imageAndFileURL
    /// 独立终端或编辑器内置终端：
    /// 同时提供 `[.png, .tiff, .fileURL, .string]`，让 `⌘V` 粘贴无空格临时 PNG 路径且 `⌃V`/CLI 仍可直接读取 PNG 二进制
    case terminalImageAndPath
}

/// 线程安全惰性临时 PNG 路径盒（仅当终端或访达实际请求路径/文件时才落盘一次，并自动清理 2 小时前的旧临时文件）
public final class ClipboardFileBox: @unchecked Sendable {
    private let lock = NSLock()
    private var cachedURL: URL?

    public init() {}

    public func materializeURL(cgImage: CGImage, scaleFactor: CGFloat) -> URL? {
        lock.lock()
        if let existing = cachedURL, FileManager.default.fileExists(atPath: existing.path) {
            lock.unlock()
            return existing
        }
        lock.unlock()
        guard let pngData = ClipboardImagePromise.encodePNG(cgImage: cgImage, scaleFactor: scaleFactor) else {
            return nil
        }
        return materializeURL(pngData: pngData)
    }

    public func materializeURL(pngData: Data) -> URL? {
        lock.lock()
        if let existing = cachedURL, FileManager.default.fileExists(atPath: existing.path) {
            lock.unlock()
            return existing
        }
        lock.unlock()

        let fm = FileManager.default
        // 使用系统临时目录（macOS 下为 /var/folders/.../T/，无论用户名是否含空格均无空格）
        let dir = fm.temporaryDirectory.appendingPathComponent("MSnipClipboard", isDirectory: true)
        try? fm.createDirectory(at: dir, withIntermediateDirectories: true)
        pruneStaleFiles(in: dir)

        let df = DateFormatter()
        df.dateFormat = "yyyyMMdd-HHmmss-SSS"
        let outURL = dir.appendingPathComponent("MSnip-\(df.string(from: Date())).png")
        do {
            try pngData.write(to: outURL, options: .atomic)
        } catch {
            MSnipLog.error(.export, "Clipboard promise PNG write failed", error: error)
            return nil
        }

        lock.lock()
        cachedURL = outURL
        lock.unlock()
        return outURL
    }

    private func pruneStaleFiles(in dir: URL, maxAgeSeconds: TimeInterval = 7200) {
        let fm = FileManager.default
        guard let urls = try? fm.contentsOfDirectory(at: dir, includingPropertiesForKeys: [.contentModificationDateKey]) else {
            return
        }
        let cutoff = Date().addingTimeInterval(-maxAgeSeconds)
        for u in urls {
            if let mtime = (try? u.resourceValues(forKeys: [.contentModificationDateKey]))?.contentModificationDate,
               mtime < cutoff {
                try? fm.removeItem(at: u)
            }
        }
    }
}

/// 独立终端、代码编辑器/IDE 与访达的 Bundle ID 识别与投影策略判定（纯函数，100% 可单测）
